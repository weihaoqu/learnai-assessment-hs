/**
 * LearnAI Assessment - Google Apps Script, FA2601 assessment v2 (HS Edition)
 *
 * Binding spec: docs/V2_CONTRACT.md (branch fa2601-v2). NOT DEPLOYED.
 * Nothing here goes live before the FA2601 modification is approved and Q
 * approves the cutover.
 *
 * What it does:
 *   Accepts one POST per test stage (pre or post) from the v2 app, validates it
 *   strictly, scores it on the server from MANIFEST.keys, and appends exactly
 *   one row to the tab 'Pre-Test v2' or 'Post-Test v2'.
 *
 * Assent handling:
 *   Only affirmative student assent ("yes") is stored. A non-assent request
 *   returns right after JSON parsing: before any other validation, Script
 *   Property read, lock, or spreadsheet access.
 *
 * v1 payloads (no "schema" field) get status 'closed' and are not stored.
 *
 * Legacy tabs:
 *   doPost and doGet never read or write the tabs named Pre-Test, Post-Test,
 *   Paired, or Rubric, and this file contains none of the v1 header, pairing,
 *   or rubric code. Only selfCheck() (test-only, run by hand from the editor)
 *   reads the legacy tabs, to hash them.
 *
 * Pairing:
 *   Nothing pairs automatically. dup_code_same_day_stage is a flag only.
 *
 * SETUP
 *   1. Paste this file into Extensions -> Apps Script of the target Sheet
 *      (the script must be bound to that Sheet).
 *   2. Project Settings -> Script Properties:
 *        ENV                'test' on the test Sheet, 'prod' on the production
 *                           Sheet. Any other value fails closed.
 *        ACTIVE_SELECTIONS  The item selection(s) this deployment accepts,
 *                           comma-separated, e.g. 'C6' or 'C6,B8'.
 *                           Production holds exactly one.
 *      A missing ENV returns {status:'error', code:'destination'}.
 *      A missing ACTIVE_SELECTIONS returns {status:'error', code:'config'}.
 *   3. Destination guard. ALLOWED_SHEET_SHA256 (below) holds the sha256 of each
 *      allowed Sheet ID, never the ID itself, so the repo never contains a
 *      Sheet ID. To add the test Sheet's hash:
 *        a. Copy the test Sheet's ID from its URL (the part between /d/ and /edit).
 *        b. Hash it on your own machine, e.g.
 *             printf %s 'PASTE_TEST_SHEET_ID' | shasum -a 256
 *           (printf, not echo: a trailing newline changes the hash).
 *        c. Paste the 64 hex characters over REPLACE_WITH_SHA256_OF_TEST_SHEET_ID.
 *      While the placeholder is there, ENV=test fails closed ('destination').
 *   4. On the TEST Sheet only: run selfCheck() from the editor before and after
 *      a trial run. It logs the v2 row counts, confirms no v2 cell holds a
 *      formula, and logs a sha256 of each legacy tab so the before/after values
 *      can be compared. It refuses to run unless ENV is 'test'.
 *   5. Deploy -> New deployment -> Web app.
 *
 * MANIFEST is generated by tools/build_items.py from the item bank. Do not edit
 * it by hand; rerun:  python3 tools/build_items.py /path/to/bank.json
 */

