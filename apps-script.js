// Form order from the Private Code. Identical in the app and the script
// (docs/V2_CONTRACT.md). The pre-test uses order[0], the post-test order[1].
function fa2601Order(code) {            // code already normalized: trim().toUpperCase()
  var h = 0x811c9dc5 >>> 0;
  for (var i = 0; i < code.length; i++) { h ^= code.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  h ^= h >>> 16; h = Math.imul(h, 0x85ebca6b) >>> 0;
  h ^= h >>> 13; h = Math.imul(h, 0xc2b2ae35) >>> 0;
  h ^= h >>> 16;
  return ((h >>> 0) & 1) === 0 ? 'AB' : 'BA';
}

// Responses
function respond_(obj) {
  return ContentService
    .createTextOutput(JSON.stringify(obj))
    .setMimeType(ContentService.MimeType.JSON);
}

// Error messages are short and fixed. They never echo the request.
function fail_(code, message) {
  return respond_({ status: 'error', code: code, message: message });
}

function reject_(code, message) {
  return { code: code, message: message };
}

// POST handler. The numbered steps follow docs/V2_CONTRACT.md.
// No spreadsheet is touched before step 8.
function doPost(e) {
  try {
    // 1. Parse the JSON body.
    var data = parseBody_(e);
    if (data === null) return fail_('bad_json', 'Request body is not a JSON object.');

    // 2. Assent. Anything other than "yes" returns here, before anything else.
    if (data.assent !== 'yes') {
      return respond_({
        status: 'not_assented',
        message: 'No affirmative assent. Nothing was recorded.'
      });
    }

    // 3. No schema field: a v1 payload. v1 is closed.
    if (!has_(data, 'schema')) {
      return respond_({ status: 'closed', message: 'This version of the test is closed.' });
    }

    // 4. Schema and assent version.
    if (data.schema !== SCHEMA) return fail_('bad_schema', 'Unsupported schema.');
    if (data.assent_version !== ASSENT_VERSION) {
      return fail_('bad_assent_version', 'Invalid assent version.');
    }

    // 5. Stage.
    if (data.stage !== 'pre' && data.stage !== 'post') return fail_('bad_stage', 'Invalid stage.');

    // 6. Private code.
    var participantId = normalizeParticipantId_(data.participant_id);
    if (participantId === null) return fail_('bad_participant_id', 'Invalid participant code.');

    // 7. Every remaining field, against MANIFEST and ACTIVE_SELECTIONS.
    var problem = validateFields_(data, participantId);
    if (problem) return fail_(problem.code, problem.message);

    // 8. Destination check (fail closed). ENV is read first so a missing or
    //    placeholder value never reaches SpreadsheetApp.
    var expectedHash = expectedSheetHash_(scriptProperty_('ENV'));
    if (!expectedHash) return fail_('destination', 'Submission destination is not configured.');
    var ss = SpreadsheetApp.getActiveSpreadsheet();
    if (!ss || sha256Hex_(String(ss.getId())) !== expectedHash) {
      return fail_('destination', 'Submission destination is not configured.');
    }

    // 9. Script lock, released in finally.
    var lock = LockService.getScriptLock();
    if (!lock.tryLock(LOCK_TIMEOUT_MS)) {
      return respond_({ status: 'busy', message: 'Server busy. Try again.' });
    }
    try {
      // 10-13.
      return respond_(storeLocked_(ss, data, participantId));
    } finally {
      lock.releaseLock();
    }
  } catch (err) {
    // Log the error type only. Never log or return the request.
    console.error('doPost internal error: ' + (err && err.name ? err.name : 'Error'));
    return fail_('internal', 'Server error.');
  }
}

// GET handler (health check).
function doGet(e) {
  return respond_({ status: 'ok', schema: SCHEMA });
}

// Steps 10-13. Runs only while holding the script lock. Returns the response object.
function storeLocked_(ss, data, participantId) {
  // 10. Idempotency: look up submission_id in both v2 tabs.
  //     A v2 tab whose header differs cannot be searched safely, so it fails
  //     closed with schema_mismatch even when it is not the target tab.
  var fingerprint = sha256Hex_(canonicalJson_(data));
  var tabs = {};
  for (var t = 0; t < V2_TABS.length; t++) {
    var name = V2_TABS[t];
    var tab = readV2Tab_(ss, name);
    if (tab.mismatch) return { status: 'error', code: 'schema_mismatch', message: 'Sheet header does not match.' };
    for (var r = 0; r < tab.rows.length; r++) {
      var row = tab.rows[r];
      if (String(row[COL.submission_id]) !== data.submission_id) continue;
      if (String(row[COL.fingerprint]) === fingerprint) {
        return { status: 'success', receipt: String(row[COL.receipt]), duplicate: true };
      }
      return { status: 'conflict', message: 'This submission ID was already used with different answers.' };
    }
    tabs[name] = tab;
  }

  // 11. Score on the server from MANIFEST.keys.
  var scored = score_(data.selection, data.form, data.answers);

  var now = new Date();
  var serverDate = Utilities.formatDate(now, TIME_ZONE, 'yyyy-MM-dd');
  var target = tabs[TAB_BY_STAGE[data.stage]];

  // Earlier rows in this tab with the same code and server date. A flag only.
  var dupCount = 0;
  for (var d = 0; d < target.rows.length; d++) {
    if (String(target.rows[d][COL.participant_id]) === participantId &&
        String(target.rows[d][COL.server_date]) === serverDate) {
      dupCount++;
    }
  }

  var record = {
    submission_id: data.submission_id,
    fingerprint: fingerprint,
    receipt: data.submission_id,
    server_received_at: now.toISOString(),
    server_date: serverDate,
    client_started_at: data.client_started_at,
    client_submitted_at: data.client_submitted_at,
    schema: data.schema,
    instrument_version: data.instrument_version,
    bank_sha256: data.bank_sha256,
    selection: data.selection,
    stage: data.stage,
    participant_id: participantId,
    order: data.order,
    form: data.form,
    assent: data.assent,
    assent_version: data.assent_version,
    coding_background: data.coding_background,
    n_items: scored.n_items,
    n_answered: scored.n_answered,
    n_skipped: scored.n_skipped,
    n_not_reached: scored.n_not_reached,
    n_correct: scored.n_correct,
    dup_code_same_day_stage: dupCount
  };
  for (var key in scored.cells) {
    if (has_(scored.cells, key)) record[key] = scored.cells[key];
  }
  var values = [];
  for (var c = 0; c < HEADER.length; c++) {
    if (!has_(record, HEADER[c])) throw new Error('Row is missing a column');
    values.push(record[HEADER[c]]);
  }

  // 12. Find or create the tab. Only a new (or completely empty) tab gets the
  //     header; a tab whose row 1 differs was already rejected in step 10.
  var sheet = target.sheet;
  if (!sheet) sheet = ss.insertSheet(TAB_BY_STAGE[data.stage]);
  if (sheet.getLastRow() === 0) writeTextRow_(sheet, 1, HEADER);
  writeTextRow_(sheet, sheet.getLastRow() + 1, values);

  // 13. Flush before the lock is released (the caller's finally).
  SpreadsheetApp.flush();
  return { status: 'success', receipt: data.submission_id, duplicate: false };
}

// Reads a v2 tab's data rows. Returns {sheet, rows, mismatch}.
// A missing tab or a completely empty tab has no rows.
function readV2Tab_(ss, name) {
  var sheet = ss.getSheetByName(name);
  if (!sheet) return { sheet: null, rows: [], mismatch: false };
  var lastRow = sheet.getLastRow();
  if (lastRow === 0) return { sheet: sheet, rows: [], mismatch: false };
  if (!headerMatches_(sheet)) return { sheet: sheet, rows: [], mismatch: true };
  var rows = lastRow > 1 ? sheet.getRange(2, 1, lastRow - 1, HEADER.length).getValues() : [];
  return { sheet: sheet, rows: rows, mismatch: false };
}

function headerMatches_(sheet) {
  if (sheet.getLastColumn() !== HEADER.length) return false;
  var first = sheet.getRange(1, 1, 1, HEADER.length).getValues()[0];
  for (var i = 0; i < HEADER.length; i++) {
    if (String(first[i]) !== HEADER[i]) return false;
  }
  return true;
}

// Formats the target row as plain text ('@') before writing, so the Sheet
// never turns a string into a formula, number, or date.
function writeTextRow_(sheet, rowIndex, values) {
  var range = sheet.getRange(rowIndex, 1, 1, values.length);
  range.setNumberFormat('@');
  range.setValues([values.slice()]);
}

// Scoring. For each of the 8 candidate pairs: _item, _choice, _score, _status.
//   answered     value "A"-"D"; score 1 if it equals the key, else 0
//   skipped      value null;    choice "" and score ""
//   not_reached  key missing;   choice "" and score ""
//   not_in_form  pair not in the selection; item "", choice "", score ""
function score_(selection, form, answers) {
  var pairs = MANIFEST.selections[selection];
  var out = { cells: {}, n_items: pairs.length, n_answered: 0, n_skipped: 0, n_not_reached: 0, n_correct: 0 };
  for (var i = 0; i < PAIR_COLUMNS.length; i++) {
    var pair = PAIR_COLUMNS[i];
    var item = '', choice = '', itemScore = '', status = 'not_in_form';
    if (pairs.indexOf(pair) !== -1) {
      item = pair + '-' + form;
      if (!has_(answers, item)) {
        status = 'not_reached';
        out.n_not_reached++;
      } else if (answers[item] === null) {
        status = 'skipped';
        out.n_skipped++;
      } else {
        status = 'answered';
        choice = answers[item];
        itemScore = choice === MANIFEST.keys[item] ? 1 : 0;
        out.n_answered++;
        out.n_correct += itemScore;
      }
    }
    out.cells[pair + '_item'] = item;
    out.cells[pair + '_choice'] = choice;
    out.cells[pair + '_score'] = itemScore;
    out.cells[pair + '_status'] = status;
  }
  return out;
}

// Validation (step 7). Returns null when valid, else {code, message}.
function validateFields_(data, participantId) {
  var keys = Object.keys(data);
  for (var i = 0; i < keys.length; i++) {
    if (BODY_FIELDS.indexOf(keys[i]) === -1) return reject_('unknown_field', 'Unexpected field.');
  }
  for (var j = 0; j < BODY_FIELDS.length; j++) {
    if (!has_(data, BODY_FIELDS[j])) return reject_('missing_field', 'Missing field: ' + BODY_FIELDS[j]);
  }

  if (typeof data.submission_id !== 'string' || !UUID_V4.test(data.submission_id)) {
    return reject_('bad_submission_id', 'Invalid submission ID.');
  }
  if (data.instrument_version !== MANIFEST.instrument_version || data.bank_sha256 !== MANIFEST.bank_sha256) {
    return reject_('manifest_mismatch', 'Item set does not match the server.');
  }
  if (typeof data.selection !== 'string' || !has_(MANIFEST.selections, data.selection)) {
    return reject_('bad_selection', 'Unknown item selection.');
  }
  var active = activeSelections_();
  if (active === null) return reject_('config', 'Server selection is not configured.');
  if (active.indexOf(data.selection) === -1) return reject_('selection_inactive', 'Item selection is not active.');

  var order = fa2601Order(participantId);
  if (data.order !== order) return reject_('bad_order', 'Form order does not match the code.');
  if (data.form !== order.charAt(data.stage === 'pre' ? 0 : 1)) {
    return reject_('bad_form', 'Form does not match the stage.');
  }

  var background = data.coding_background;
  var backgroundOk = typeof background === 'string' &&
    (data.stage === 'pre' ? CODING_BACKGROUNDS.indexOf(background) !== -1 : background === '');
  if (!backgroundOk) return reject_('bad_coding_background', 'Invalid coding background.');

  if (!isPlainObject_(data.answers)) return reject_('bad_answers', 'Invalid answers.');
  var formItems = formItemIds_(data.selection, data.form);
  var answerKeys = Object.keys(data.answers);
  for (var k = 0; k < answerKeys.length; k++) {
    if (formItems.indexOf(answerKeys[k]) === -1) return reject_('bad_answers', 'Answer for an item not in the form.');
    var value = data.answers[answerKeys[k]];
    if (value !== null && CHOICES.indexOf(value) === -1) return reject_('bad_answer_value', 'Invalid answer value.');
  }

  if (!isIsoUtc_(data.client_started_at) || !isIsoUtc_(data.client_submitted_at)) {
    return reject_('bad_timestamp', 'Invalid timestamp.');
  }
  return null;
}

// ACTIVE_SELECTIONS as a list, or null when missing or misconfigured (fail closed).
// Every listed selection must exist in MANIFEST, use only the 8 candidate
// pairs, and have a key for both forms of each pair.
function activeSelections_() {
  var raw = scriptProperty_('ACTIVE_SELECTIONS');
  if (raw === null) return null;
  var parts = raw.split(',');
  var list = [];
  for (var i = 0; i < parts.length; i++) {
    var id = parts[i].trim();
    if (id) list.push(id);
  }
  if (list.length === 0) return null;
  for (var j = 0; j < list.length; j++) {
    if (!has_(MANIFEST.selections, list[j])) return null;
    var pairs = MANIFEST.selections[list[j]];
    for (var p = 0; p < pairs.length; p++) {
      if (PAIR_COLUMNS.indexOf(pairs[p]) === -1) return null;
      if (CHOICES.indexOf(MANIFEST.keys[pairs[p] + '-A']) === -1) return null;
      if (CHOICES.indexOf(MANIFEST.keys[pairs[p] + '-B']) === -1) return null;
    }
  }
  return list;
}

// A form's item IDs: <pair>-<form> for each pair, in selection order.
function formItemIds_(selection, form) {
  var pairs = MANIFEST.selections[selection];
  var ids = [];
  for (var i = 0; i < pairs.length; i++) ids.push(pairs[i] + '-' + form);
  return ids;
}

// Destination: the allowlisted hash for ENV, or null (missing ENV, unknown
// ENV, or a placeholder that is not 64 hex characters).
function expectedSheetHash_(env) {
  if (typeof env !== 'string') return null;
  env = env.trim();
  if (!has_(ALLOWED_SHEET_SHA256, env)) return null;
  var hash = ALLOWED_SHEET_SHA256[env];
  return SHA256_HEX.test(hash) ? hash : null;
}

// Helpers
function parseBody_(e) {
  if (!e || !e.postData || typeof e.postData.contents !== 'string') return null;
  var data;
  try {
    data = JSON.parse(e.postData.contents);
  } catch (err) {
    return null;
  }
  return isPlainObject_(data) ? data : null;
}

function normalizeParticipantId_(value) {
  if (typeof value !== 'string') return null;
  var code = value.trim().toUpperCase();
  return /^([0-9]|[1-9][0-9]|100)[A-Z]$/.test(code) ? code : null;
}

// ISO-8601 UTC, e.g. 2026-11-07T14:03:00.000Z, and a real calendar time.
function isIsoUtc_(value) {
  if (typeof value !== 'string' || !ISO_UTC.test(value)) return false;
  var ms = new Date(value).getTime();
  if (isNaN(ms)) return false;
  var withMillis = value.length === 20 ? value.slice(0, 19) + '.000Z' : value;
  return new Date(ms).toISOString() === withMillis;
}

function isPlainObject_(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function has_(obj, key) {
  return Object.prototype.hasOwnProperty.call(obj, key);
}

function scriptProperty_(name) {
  return PropertiesService.getScriptProperties().getProperty(name);
}

// Canonical JSON: object keys sorted recursively, no whitespace.
function canonicalJson_(value) {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  var parts = [];
  if (Array.isArray(value)) {
    for (var i = 0; i < value.length; i++) parts.push(canonicalJson_(value[i]));
    return '[' + parts.join(',') + ']';
  }
  var keys = Object.keys(value).sort();
  for (var j = 0; j < keys.length; j++) {
    parts.push(JSON.stringify(keys[j]) + ':' + canonicalJson_(value[keys[j]]));
  }
  return '{' + parts.join(',') + '}';
}

// sha256 as lower-case hex. computeDigest returns signed bytes (-128..127).
function sha256Hex_(text) {
  var bytes = Utilities.computeDigest(Utilities.DigestAlgorithm.SHA_256, text, Utilities.Charset.UTF_8);
  var hex = '';
  for (var i = 0; i < bytes.length; i++) {
    var b = bytes[i] & 0xff;
    hex += (b < 16 ? '0' : '') + b.toString(16);
  }
  return hex;
}

/**
 * TEST-ONLY. Run by hand from the editor on the TEST Sheet, before and after a
 * trial run, and compare the two logs. Never called by doPost or doGet.
 *   - each v2 tab: row count, header check, and that getFormulas() is all empty;
 *   - each legacy tab present (Pre-Test, Post-Test, Paired, Rubric): its size
 *     and a sha256 of its values, read only.
 * Refuses to run unless ENV is 'test' and this Sheet matches the test hash.
 */
function selfCheck() {
  var env = scriptProperty_('ENV');
  if (env === null || env.trim() !== 'test') {
    throw new Error('selfCheck refuses to run: Script Property ENV must be test.');
  }
  var expectedHash = expectedSheetHash_('test');
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  if (!expectedHash || !ss || sha256Hex_(String(ss.getId())) !== expectedHash) {
    throw new Error('selfCheck refuses to run: this Sheet does not match the test Sheet hash.');
  }

  var report = { v2: {}, legacy: {} };
  for (var t = 0; t < V2_TABS.length; t++) {
    var name = V2_TABS[t];
    var sheet = ss.getSheetByName(name);
    if (!sheet) {
      report.v2[name] = { present: false };
      Logger.log(name + ': not present');
      continue;
    }
    var lastRow = sheet.getLastRow();
    var lastCol = sheet.getLastColumn();
    var formulasEmpty = true;
    if (lastRow > 0 && lastCol > 0) {
      var formulas = sheet.getRange(1, 1, lastRow, lastCol).getFormulas();
      for (var r = 0; r < formulas.length; r++) {
        for (var c = 0; c < formulas[r].length; c++) {
          if (formulas[r][c] !== '') formulasEmpty = false;
        }
      }
    }
    var headerOk = lastRow > 0 && headerMatches_(sheet);
    report.v2[name] = {
      present: true, rows: lastRow, data_rows: Math.max(lastRow - 1, 0),
      header_ok: headerOk, formulas_empty: formulasEmpty
    };
    Logger.log(name + ': rows=' + lastRow + ' data_rows=' + Math.max(lastRow - 1, 0) +
      ' header_ok=' + headerOk + ' formulas_empty=' + formulasEmpty);
  }

  for (var l = 0; l < LEGACY_TABS.length; l++) {
    var legacyName = LEGACY_TABS[l];
    var legacy = ss.getSheetByName(legacyName);
    if (!legacy) {
      report.legacy[legacyName] = { present: false };
      Logger.log(legacyName + ': not present');
      continue;
    }
    var rows = legacy.getLastRow();
    var cols = legacy.getLastColumn();
    var values = rows > 0 && cols > 0 ? legacy.getRange(1, 1, rows, cols).getValues() : [];
    var hash = sha256Hex_(JSON.stringify(values));
    report.legacy[legacyName] = { present: true, rows: rows, cols: cols, sha256: hash };
    Logger.log(legacyName + ': rows=' + rows + ' cols=' + cols + ' sha256=' + hash);
  }
  return report;
}
