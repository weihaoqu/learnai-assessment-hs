#!/usr/bin/env python3
"""Generate the v2 item files from the candidate bank (docs/V2_CONTRACT.md).

    python3 tools/build_items.py /path/to/bank.json

Writes items-v2.js (stems and options, no keys) and replaces the block between
the GENERATED MANIFEST markers in apps-script.js (keys, for server scoring).
Both carry the bank's version and sha256, so the app and the script can be
checked against each other.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = '// BEGIN GENERATED MANIFEST', '// END GENERATED MANIFEST'
# Used only while a bank has no "selections" block (draft-0.2).
DEFAULT_SELECTIONS = {
    'C6': ['J1', 'G1', 'C1', 'P2', 'C3', 'G2'],
    'B8': ['J1', 'G1', 'C1', 'P2', 'J3', 'G2', 'C3', 'P3'],
}


def load(bank_path):
    raw = Path(bank_path).read_bytes()
    bank = json.loads(raw)
    selections = bank.get('selections', DEFAULT_SELECTIONS)
    pairs = {p['id']: p for p in bank['pairs']}
    items, keys = {}, {}
    for pair_id in sorted({p for sel in selections.values() for p in sel}):
        if pair_id not in pairs:
            raise SystemExit(f'Selection names a missing pair: {pair_id}')
        pair = pairs[pair_id]
        if pair.get('status') == 'quarantined':
            raise SystemExit(f'Selection uses a quarantined pair: {pair_id}')
        members = {m['id']: m for m in pair['members']}
        for form in 'AB':
            item_id = f'{pair_id}-{form}'
            member = members.get(item_id)
            if member is None or len(member['options']) != 4:
                raise SystemExit(f'{item_id} is missing or does not have four options')
            if sum(o['key'] is True for o in member['options']) != 1:
                raise SystemExit(f'{item_id} must have exactly one key')
            items[item_id] = {'stem': member['stem'], 'options': [o['text'] for o in member['options']]}
            keys[item_id] = 'ABCD'[[o['key'] for o in member['options']].index(True)]
    meta = {'instrument_version': bank['version'], 'bank_sha256': hashlib.sha256(raw).hexdigest(),
            'selections': selections}
    return meta, items, keys


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    meta, items, keys = load(sys.argv[1])
    client = dict(meta, items=items)
    (ROOT / 'items-v2.js').write_text(
        '// Generated by tools/build_items.py. Do not edit. No answer keys.\n'
        f'window.FA2601_ITEMS = {json.dumps(client, indent=1, ensure_ascii=False)};\n', encoding='utf-8')
    script_path = ROOT / 'apps-script.js'
    script = script_path.read_text(encoding='utf-8')
    if script.count(BEGIN) != 1 or script.count(END) != 1:
        raise SystemExit('apps-script.js needs exactly one pair of GENERATED MANIFEST markers')
    head, rest = script.split(BEGIN)
    _, tail = rest.split(END)
    block = f'{BEGIN}\nvar MANIFEST = {json.dumps(dict(meta, keys=keys), indent=1)};\n{END}'
    script_path.write_text(head + block + tail, encoding='utf-8')
    # Pin the page to this build: the app refuses to start unless items-v2.js has
    # the version in ?v=, and &h= busts caches when the bank changes.
    page_path = ROOT / 'index.html'
    page = page_path.read_text(encoding='utf-8')
    tag = f"?v={meta['instrument_version']}&amp;h={meta['bank_sha256'][:12]}"
    new_page, n = re.subn(r'(src="(?:items|config)-v2\.js)\?v=[^"]*"', lambda m: m.group(1) + tag + '"', page)
    if n != 2:
        raise SystemExit('index.html needs exactly two v2 script tags (items-v2.js, config-v2.js)')
    page_path.write_text(new_page, encoding='utf-8')
    print(f"{meta['instrument_version']} {meta['bank_sha256'][:12]}: {len(items)} items, "
          f"selections {', '.join(f'{k}={len(v)}' for k, v in meta['selections'].items())}")


if __name__ == '__main__':
    main()
